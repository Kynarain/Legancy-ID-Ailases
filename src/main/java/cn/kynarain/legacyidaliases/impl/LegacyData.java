package cn.kynarain.legacyidaliases.impl;

import cn.kynarain.legacyidaliases.api.LegacyId;
import cn.kynarain.legacyidaliases.api.LegacyIdTarget;
import cn.kynarain.legacyidaliases.api.LegacyRegistry;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Collections;
import java.util.EnumMap;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import net.fabricmc.loader.api.FabricLoader;
import net.minecraft.util.Identifier;
import org.jetbrains.annotations.Nullable;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Loads the bundled datasets (generated by {@code tools/generate_data.py}) and the user mapping
 * files from {@code config/legacy_id_aliases/}.
 */
public final class LegacyData {
	private static final Logger LOGGER = LoggerFactory.getLogger("Legacy ID Aliases/Data");
	private static final String RESOURCE_ROOT = "/data/legacy_id_aliases/legacy_ids/";
	private static final String CONFIG_FOLDER = "legacy_id_aliases";
	/**
	 * The sample mapping is written with a double extension so it is not loaded as a real mapping:
	 * everything ending in {@code .json} is treated as user configuration.
	 */
	private static final String EXAMPLE_FILE = "example.json.example";
	private static final String EXAMPLE_JSON = """
		{
		  "//": "Legacy ID Aliases - user mappings. Every *.json file in this folder is loaded.",
		  "//format": "registries -> <registry id> -> <id or id:meta> -> <identifier or {id, potion}>",
		  "schema": 1,
		  "registries": {
		    "item": {
		      "35:14": "minecraft:red_wool",
		      "1000": "minecraft:paper",
		      "373:5": { "id": "minecraft:potion", "potion": "minecraft:healing" }
		    },
		    "block": {
		      "196": "minecraft:oak_sign"
		    },
		    "entity_type": {
		      "60": "minecraft:creeper"
		    }
		  }
		}
		""";

	private static boolean bundledLoaded;
	private static boolean userLoaded;
	private static Map<Integer, String> itemNames = Map.of();
	private static Map<LegacyRegistry, Map<Integer, String>> registryNames = Map.of();
	private static List<AddedItem> additions = List.of();
	private static Map<LegacyRegistry, Map<String, String>> renames = Map.of();
	private static Map<LegacyRegistry, Map<LegacyId, LegacyIdTarget>> bundledTables = Map.of();
	private static Map<LegacyRegistry, Map<LegacyId, LegacyIdTarget>> userTables = Map.of();
	private static Path configDirectory;

	private LegacyData() {
	}

	public record AddedItem(String name, String since) {
	}

	public static synchronized void load() {
		if (!bundledLoaded) {
			loadBundled();
			bundledLoaded = true;
		}
		if (!userLoaded) {
			reloadUser();
		}
	}

	public static synchronized void reloadUser() {
		userLoaded = true;
		configDirectory = FabricLoader.getInstance().getConfigDir().resolve(CONFIG_FOLDER);
		Map<LegacyRegistry, Map<LegacyId, LegacyIdTarget>> loaded = new EnumMap<>(LegacyRegistry.class);
		List<Path> files = new ArrayList<>();
		try {
			Files.createDirectories(configDirectory);
			try (var stream = Files.list(configDirectory)) {
				stream.filter(path -> path.getFileName().toString().endsWith(".json"))
					.filter(Files::isRegularFile)
					.sorted()
					.forEach(files::add);
			}
		} catch (IOException exception) {
			LOGGER.warn("Could not read the mapping folder {}", configDirectory, exception);
		}
		if (files.isEmpty()) {
			writeExample();
		}
		for (Path file : files) {
			try (Reader reader = Files.newBufferedReader(file, StandardCharsets.UTF_8)) {
				readMappingFile(JsonParser.parseReader(reader), file.getFileName().toString(), loaded);
			} catch (Exception exception) {
				LOGGER.warn("Skipping invalid mapping file {}", file, exception);
			}
		}
		userTables = freezeTables(loaded);
		LOGGER.info("Loaded user mappings from {} ({} registries)", configDirectory, userTables.size());
	}

	private static void writeExample() {
		Path example = configDirectory.resolve(EXAMPLE_FILE);
		try {
			Files.writeString(example, EXAMPLE_JSON, StandardCharsets.UTF_8);
			LOGGER.info("Wrote a sample mapping to {} (copy it to <name>.json to activate it)", example);
		} catch (IOException exception) {
			LOGGER.debug("Could not write the example mapping file", exception);
		}
	}

	private static void loadBundled() {
		itemNames = readIntegerNameMap("legacy_item_names.json");
		registryNames = readRegistryNames();
		additions = readAdditions();
		renames = readRenames();
		bundledTables = readExtraTables("extra_tables.json");
	}

	private static Map<Integer, String> readIntegerNameMap(String resource) {
		JsonElement root = readResource(resource);
		Map<Integer, String> map = new LinkedHashMap<>();
		if (root == null || !root.isJsonObject()) {
			return Map.of();
		}
		for (Map.Entry<String, JsonElement> entry : root.getAsJsonObject().entrySet()) {
			try {
				map.put(Integer.parseInt(entry.getKey()), entry.getValue().getAsString());
			} catch (NumberFormatException exception) {
				LOGGER.warn("Invalid legacy id '{}' in {}", entry.getKey(), resource);
			}
		}
		return Collections.unmodifiableMap(map);
	}

	private static Map<LegacyRegistry, Map<Integer, String>> readRegistryNames() {
		JsonElement root = readResource("legacy_registry_names.json");
		Map<LegacyRegistry, Map<Integer, String>> map = new EnumMap<>(LegacyRegistry.class);
		if (root == null || !root.isJsonObject()) {
			return Map.of();
		}
		for (Map.Entry<String, JsonElement> registryEntry : root.getAsJsonObject().entrySet()) {
			LegacyRegistry registry = LegacyRegistry.byId(registryEntry.getKey()).orElse(null);
			if (registry == null) {
				LOGGER.warn("Unknown registry '{}' in legacy_registry_names.json", registryEntry.getKey());
				continue;
			}
			Map<Integer, String> names = new TreeMap<>();
			for (Map.Entry<String, JsonElement> entry : registryEntry.getValue().getAsJsonObject().entrySet()) {
				try {
					names.put(Integer.parseInt(entry.getKey()), entry.getValue().getAsString());
				} catch (NumberFormatException exception) {
					LOGGER.warn("Invalid legacy id '{}' for {}", entry.getKey(), registry.id());
				}
			}
			map.put(registry, Collections.unmodifiableMap(names));
		}
		return Map.copyOf(map);
	}

	private static List<AddedItem> readAdditions() {
		JsonElement root = readResource("modern_item_additions.json");
		if (root == null || !root.isJsonArray()) {
			return List.of();
		}
		JsonArray array = root.getAsJsonArray();
		List<AddedItem> list = new ArrayList<>(array.size());
		for (JsonElement element : array) {
			if (!element.isJsonObject()) {
				continue;
			}
			JsonObject object = element.getAsJsonObject();
			String name = object.has("name") ? object.get("name").getAsString() : null;
			String since = object.has("since") ? object.get("since").getAsString() : "unknown";
			if (name != null && !name.isBlank()) {
				list.add(new AddedItem(name, since));
			}
		}
		return List.copyOf(list);
	}

	private static Map<LegacyRegistry, Map<String, String>> readRenames() {
		JsonElement root = readResource("renames.json");
		Map<LegacyRegistry, Map<String, String>> map = new EnumMap<>(LegacyRegistry.class);
		if (root == null || !root.isJsonObject()) {
			return Map.of();
		}
		for (Map.Entry<String, JsonElement> entry : root.getAsJsonObject().entrySet()) {
			LegacyRegistry registry = LegacyRegistry.byId(entry.getKey()).orElse(null);
			if (registry == null || !entry.getValue().isJsonObject()) {
				continue;
			}
			Map<String, String> table = new HashMap<>();
			for (Map.Entry<String, JsonElement> rename : entry.getValue().getAsJsonObject().entrySet()) {
				table.put(rename.getKey(), rename.getValue().getAsString());
			}
			map.put(registry, Map.copyOf(table));
		}
		return Map.copyOf(map);
	}

	private static Map<LegacyRegistry, Map<LegacyId, LegacyIdTarget>> readExtraTables(String resource) {
		JsonElement root = readResource(resource);
		if (root == null) {
			return Map.of();
		}
		Map<LegacyRegistry, Map<LegacyId, LegacyIdTarget>> raw = new EnumMap<>(LegacyRegistry.class);
		readMappingFile(root, resource, raw);
		return freezeTables(raw);
	}

	/**
	 * Reads the user facing format: {@code {"registries": {"item": {"35:14": "minecraft:red_wool"}}}}.
	 * A mapping file may also omit the {@code registries} wrapper.
	 */
	private static void readMappingFile(
		JsonElement root,
		String source,
		Map<LegacyRegistry, Map<LegacyId, LegacyIdTarget>> target
	) {
		if (root == null || !root.isJsonObject()) {
			LOGGER.warn("{} is not a JSON object", source);
			return;
		}
		JsonObject object = root.getAsJsonObject();
		JsonObject registries = object.has("registries") && object.get("registries").isJsonObject()
			? object.getAsJsonObject("registries")
			: object;
		for (Map.Entry<String, JsonElement> registryEntry : registries.entrySet()) {
			if (!registryEntry.getValue().isJsonObject()) {
				continue;
			}
			LegacyRegistry registry = LegacyRegistry.byId(registryEntry.getKey()).orElse(null);
			if (registry == null) {
				LOGGER.warn("{}: unknown registry '{}'", source, registryEntry.getKey());
				continue;
			}
			Map<LegacyId, LegacyIdTarget> table = target.computeIfAbsent(registry, key -> new LinkedHashMap<>());
			for (Map.Entry<String, JsonElement> entry : registryEntry.getValue().getAsJsonObject().entrySet()) {
				LegacyId legacyId;
				try {
					legacyId = LegacyId.parse(entry.getKey());
				} catch (IllegalArgumentException exception) {
					LOGGER.warn("{}: invalid legacy id '{}'", source, entry.getKey());
					continue;
				}
				LegacyIdTarget mapping = parseTarget(entry.getValue());
				if (mapping == null) {
					LOGGER.warn("{}: invalid mapping for '{}'", source, entry.getKey());
					continue;
				}
				table.put(legacyId, mapping);
			}
		}
	}

	/**
	 * Parses a mapping value: either a plain identifier string, or an object with {@code id} and the
	 * optional {@code potion} shortcut for potions (the variant lives in a data component, not in the
	 * identifier).
	 */
	@Nullable
	private static LegacyIdTarget parseTarget(JsonElement element) {
		if (element.isJsonPrimitive()) {
			Identifier identifier = parseIdentifier(element.getAsString());
			return identifier == null ? null : LegacyIdTarget.of(identifier);
		}
		if (!element.isJsonObject()) {
			return null;
		}
		JsonObject object = element.getAsJsonObject();
		JsonElement idElement = object.has("id")
			? object.get("id")
			: object.has("result") ? object.get("result") : null;
		if (idElement == null) {
			return null;
		}
		Identifier identifier = parseIdentifier(idElement.getAsString());
		if (identifier == null) {
			return null;
		}
		Identifier potion = object.has("potion") ? parseIdentifier(object.get("potion").getAsString()) : null;
		return potion == null ? LegacyIdTarget.of(identifier) : LegacyIdTarget.ofPotion(identifier, potion);
	}

	public static Identifier parseIdentifier(String value) {
		String trimmed = value.trim();
		if (trimmed.isEmpty()) {
			return null;
		}
		if (trimmed.indexOf(':') < 0) {
			trimmed = "minecraft:" + trimmed;
		}
		return Identifier.tryParse(trimmed);
	}

	private static Map<LegacyRegistry, Map<LegacyId, LegacyIdTarget>> freezeTables(
		Map<LegacyRegistry, Map<LegacyId, LegacyIdTarget>> raw
	) {
		Map<LegacyRegistry, Map<LegacyId, LegacyIdTarget>> result = new EnumMap<>(LegacyRegistry.class);
		for (Map.Entry<LegacyRegistry, Map<LegacyId, LegacyIdTarget>> entry : raw.entrySet()) {
			result.put(entry.getKey(), Collections.unmodifiableMap(new LinkedHashMap<>(entry.getValue())));
		}
		return Collections.unmodifiableMap(result);
	}

	private static JsonElement readResource(String name) {
		String path = RESOURCE_ROOT + name;
		try (InputStream stream = LegacyData.class.getResourceAsStream(path)) {
			if (stream == null) {
				LOGGER.debug("Bundled dataset {} is missing", path);
				return null;
			}
			try (Reader reader = new InputStreamReader(stream, StandardCharsets.UTF_8)) {
				return JsonParser.parseReader(reader);
			}
		} catch (IOException | RuntimeException exception) {
			LOGGER.warn("Could not read bundled dataset {}", path, exception);
			return null;
		}
	}

	public static Map<Integer, String> itemNames() {
		return itemNames;
	}

	public static Map<Integer, String> registryNames(LegacyRegistry registry) {
		return registryNames.getOrDefault(registry, Map.of());
	}

	public static List<AddedItem> additions() {
		return additions;
	}

	public static Map<LegacyId, LegacyIdTarget> bundledTable(LegacyRegistry registry) {
		return bundledTables.getOrDefault(registry, Map.of());
	}

	public static Map<LegacyId, LegacyIdTarget> userTable(LegacyRegistry registry) {
		return userTables.getOrDefault(registry, Map.of());
	}

	/**
	 * Applies the rename table of a registry, e.g. the 1.13 name {@code minecraft:rose_red} becomes
	 * {@code minecraft:red_dye}.
	 */
	public static String rename(LegacyRegistry registry, String identifier) {
		if (identifier == null || identifier.isEmpty()) {
			return null;
		}
		Identifier parsed = parseIdentifier(identifier);
		if (parsed == null) {
			return null;
		}
		String renamed = renames.getOrDefault(registry, Map.of()).get(parsed.getPath());
		return renamed == null ? parsed.toString() : "minecraft:" + renamed;
	}

	public static Path configDirectory() {
		return configDirectory;
	}
}
